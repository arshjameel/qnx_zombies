int map_is_wall(int mx, int my)
{
    if (mx < 0 || mx >= MAP_W || my < 0 || my >= MAP_ROWS) return 1;
    return g_map[my][mx] != 0;
}

int map_tile(int mx, int my)
{
    if (mx < 0 || mx >= MAP_W || my < 0 || my >= MAP_ROWS) return 1;
    return (int)g_map[my][mx];
}
